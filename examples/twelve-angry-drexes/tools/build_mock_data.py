#!/usr/bin/env python3
"""Build mocks/lawwiki-data.js from data/statutes/*.json and data/rulings/*.json so the mocks show real records."""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from engine import roles  # noqa: E402

out = {}
for f in sorted((ROOT / "data" / "statutes").glob("*_*.json")):
    if f.name.startswith("db_"):  # database manifests, not statutes
        continue
    d = json.loads(f.read_text())
    key = f"{d['jurisdiction']}/{d['code']}/{d['section']}"
    out[key] = {"citation": d["citation"], "title": d["title"], "url": d["lawwiki_url"],
                "source_version": d["source_version"], "chars": len(d["text"] or "")}
# practice-area roles (engine/roles.py), so the mocks ask the same intake questions and next-step options
role_table = {"groups": roles.GROUPS, "roles": {rid: {k: r[k] for k in ("label", "team", "lens", "finding", "burden", "side", "next_steps")}
                                                | {"group": roles.GROUPS[r["group"]], "scope": r["scope"]} for rid, r in roles.ROLES.items()}}
rulings = {}
for f in sorted((ROOT / "data" / "rulings").glob("*.json")):
    d = json.loads(f.read_text())
    ex = {e["label"]: e["text"] for e in d["excerpts"]}  # passages cut from the ruling text by tools/fetch_ruling.py
    rulings[d["name"]] = {"cite": d["short_cite"], "court": d["court"], "date": d["date"], "docket": d["docket_number"],
                          "excerpt": ex["rule"], "holding": ex["holding"], "disposition": ex["disposition"],
                          "source": f'{d["source"]["dataset"]}, {d["source"]["license"]}', "real": True}
(ROOT / "mocks" / "lawwiki-data.js").write_text(
    "/* Generated by tools/build_mock_data.py from data/statutes (LawWiki text) and data/rulings. Do not edit. */\n"
    "window.TAD_STATUTES = " + json.dumps(out, indent=1, ensure_ascii=False) + ";\n"
    "window.TAD_RULINGS = " + json.dumps(rulings, indent=1, ensure_ascii=False) + ";\n"
    "window.TAD_ROLES = " + json.dumps(role_table, indent=1, ensure_ascii=False) + ";\n")
print(len(out), "statutes,", len(rulings), "rulings ->", "mocks/lawwiki-data.js")
